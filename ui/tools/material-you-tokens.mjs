import { writeFileSync } from 'node:fs';
import { Hct, MaterialDynamicColors, SchemeTonalSpot, argbFromHex, hexFromArgb } from '@material/material-color-utilities';

const roles = ['primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer', 'secondaryContainer', 'onSecondaryContainer', 'surface', 'surfaceContainerLow', 'surfaceContainer', 'surfaceContainerHigh', 'onSurface', 'onSurfaceVariant', 'outlineVariant'];
const variable = role => `--md-${role.replace(/[A-Z]/g, letter => `-${letter.toLowerCase()}`)}`;
const schemes = [
  [':root, :root.theme-light', '#20553f', false],
  [':root.theme-dark', '#20553f', true],
  [':root :is(.expo-page, .new-version-shell, .dev-console)', '#35677f', false],
  [':root.theme-dark :is(.expo-page, .new-version-shell, .dev-console)', '#35677f', true],
];
const css = schemes.map(([selector, seed, dark]) => {
  const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(seed)), dark, 0);
  const gold = new SchemeTonalSpot(Hct.fromInt(argbFromHex('#886423')), dark, 0);
  return `${selector} {\n  /* Source ${seed}; ${dark ? 'dark' : 'light'} Material You tonal spot. */\n${roles.map(role => `  ${variable(role)}: ${hexFromArgb(MaterialDynamicColors[role].getArgb(scheme))};`).join('\n')}\n  /* Gold accent source #886423. */\n  --md-gold-container: ${hexFromArgb(MaterialDynamicColors.primaryContainer.getArgb(gold))};\n  --md-on-gold-container: ${hexFromArgb(MaterialDynamicColors.onPrimaryContainer.getArgb(gold))};\n}`;
}).join('\n\n');
writeFileSync(new URL('../src/styles/material-you-tokens.css', import.meta.url), `/* Generated by npm run design:palette using Google's Material Color Utilities. */\n${css}\n`);
console.log('[design:palette] Generated light and dark Material You roles for both interfaces.');
