 OUT.joinpath('report.json').write_text(json.dumps({'checks':checks,'pageErrors':errors,'version':json.loads((Path(__file__).resolve().parents[3]/'package.json').read_text())['version'],'date':'2026-10-13'},ensure_ascii=False,indent=2)+'\n')
