   await page.reload(wait_until='domcontentloaded')
   await expect(page.get_by_text('诊断记忆 · 已连接',exact=False)).to_be_visible()
   await page.locator('summary').filter(has_text='诊断记忆').click()
   await expect(page.get_by_label('设备名称（区分不同车辆）',exact=True)).to_have_value(f'验收车辆-{port}')
