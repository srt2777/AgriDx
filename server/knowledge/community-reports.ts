import { KNOWLEDGE_ROLES } from '../../shared/knowledge-catalog';
import {
  COMMUNITY_REPORT_EXCLUDED_BRAND,
  COMMUNITY_REPORT_FORMULA_VERSION,
  COMMUNITY_REPORT_LIMITATIONS,
  COMMUNITY_REPORT_ROLE_LABELS,
  describeCommunityReportStaleness,
  isCommunityReportCurrent,
  type CommunityReport,
  type CommunityReportSentence,
  type CommunityReportSet,
  type CommunityReportSource,
} from '../../shared/knowledge-community-reports';
import type { KnowledgeChunk } from './types';
import { loadKnowledgeSnapshot, type KnowledgeSnapshot } from './snapshot';

const INFORMATION_TYPES = new Set(['资料索引', '资料核验', '机型资料', '资料缺口', '系统适用边界']);

const cache = new WeakMap<KnowledgeSnapshot, CommunityReportSet>();

/** Entry title as the catalog shows it: the heading after the entry-id separator. */
function entryTitle(chunk: KnowledgeChunk): string {
  const title = chunk.heading.split('｜').slice(1).join('｜');
  return title || chunk.heading;
}

function toSource(chunk: KnowledgeChunk): CommunityReportSource {
  return {
    entry_id: chunk.entryId!,
    source_id: chunk.sourceId!,
    pages: chunk.pages ? { ...chunk.pages } : null,
    locator: chunk.locator ?? '',
  };
}

/** At most two example titles; the full cited set stays in `sources`. */
function examples(chunks: readonly KnowledgeChunk[]): string {
  return chunks.slice(0, 2).map((chunk) => `《${entryTitle(chunk)}》`).join('');
}

function sentence(kind: CommunityReportSentence['kind'], text: string, chunks: readonly KnowledgeChunk[]): CommunityReportSentence {
  return { kind, text, sources: chunks.map(toSource) };
}

/**
 * Build one report per catalog (brand, model, component) group with entries.
 * Grouping, order and membership are taken from the catalog and the snapshot's
 * hierarchy links — no second taxonomy. Sentences are deterministic counts and
 * labels over the cited entries only; nothing is generated by an LLM.
 */
export function buildCommunityReports(snapshot: KnowledgeSnapshot): CommunityReportSet {
  const catalog = snapshot.getCatalog();
  const archive = snapshot.chunks.filter((chunk) => chunk.entryId && chunk.diagnosticEvidence !== false);
  const byId = new Map<string, KnowledgeChunk>();
  for (const chunk of archive) {
    if (chunk.entryId && !byId.has(chunk.entryId)) byId.set(chunk.entryId, chunk);
  }
  const entries = [...byId.values()].sort((a, b) => a.entryId!.localeCompare(b.entryId!));

  const grouped = new Map<string, KnowledgeChunk[]>();
  for (const chunk of entries) {
    if (!chunk.brand || !chunk.sourceId) continue;
    if (chunk.brand === COMMUNITY_REPORT_EXCLUDED_BRAND) continue;
    const models = snapshot.entryModels.get(chunk.entryId!) ?? [];
    const components = snapshot.retrievalOrganization.entryComponents[chunk.entryId!] ?? [];
    for (const model of models) {
      for (const componentId of components) {
        const key = JSON.stringify([chunk.brand, model, componentId]);
        const list = grouped.get(key) ?? [];
        list.push(chunk);
        grouped.set(key, list);
      }
    }
  }

  const reports: CommunityReport[] = [];
  const covered = new Set<string>();
  for (const brand of catalog.brands) {
    if (brand.name === COMMUNITY_REPORT_EXCLUDED_BRAND) continue;
    for (const model of brand.models) {
      for (const component of model.components) {
        if (component.entryCount === 0) continue;
        const key = JSON.stringify([brand.name, model.name, component.id]);
        const group = grouped.get(key) ?? [];
        if (group.length === 0) throw new Error(`社区报告分组与目录不一致：${key} 在目录中有条目但未聚合到条目`);
        if (group.length !== component.entryCount) {
          throw new Error(`社区报告分组计数与目录不一致：${key} 目录 ${component.entryCount} 条，聚合 ${group.length} 条`);
        }
        reports.push(buildReport(snapshot, brand.name, model.name, component.id, component.name, group));
        for (const chunk of group) covered.add(chunk.entryId!);
      }
    }
  }
  const reportIds = new Set(reports.map((report) => report.id));
  for (const key of grouped.keys()) {
    if (!reportIds.has(key)) throw new Error(`社区报告分组与目录不一致：${key} 未出现在目录中`);
  }

  const result: CommunityReportSet = {
    kbVersion: snapshot.kbVersion,
    snapshotSha: snapshot.snapshotSha,
    formulaVersion: COMMUNITY_REPORT_FORMULA_VERSION,
    status: 'current',
    reports,
    totalReports: reports.length,
    totalEntries: covered.size,
    degraded: [],
    limitations: [...COMMUNITY_REPORT_LIMITATIONS],
  };
  for (const report of reports) Object.freeze(report.sentences);
  Object.freeze(reports);
  return Object.freeze(result);
}

function buildReport(
  snapshot: KnowledgeSnapshot,
  brand: string,
  model: string,
  componentId: string,
  componentName: string,
  group: KnowledgeChunk[],
): CommunityReport {
  const sentences: CommunityReportSentence[] = [];
  const sources = new Set(group.map((chunk) => chunk.sourceId!));
  sentences.push(sentence('overview',
    `本组共收录 ${group.length} 条归档条目，来自 ${sources.size} 份来源。`, group));

  const byType = new Map<string, KnowledgeChunk[]>();
  for (const chunk of group) {
    const type = chunk.entryType ?? '未分类';
    const list = byType.get(type) ?? [];
    list.push(chunk);
    byType.set(type, list);
  }
  for (const type of [...byType.keys()].sort((a, b) => a.localeCompare(b, 'zh-CN'))) {
    const list = byType.get(type)!;
    sentences.push(sentence('entry-type',
      `其中「${type}」${list.length} 条，例如${examples(list)}。`, list));
  }

  for (const role of KNOWLEDGE_ROLES) {
    const list = group.filter((chunk) => chunk.roles?.includes(role));
    if (!list.length) continue;
    sentences.push(sentence('role',
      `已标注角色的条目中，「${COMMUNITY_REPORT_ROLE_LABELS[role]}」${list.length} 条，例如${examples(list)}。`, list));
  }

  const bySource = new Map<string, KnowledgeChunk[]>();
  for (const chunk of group) {
    const list = bySource.get(chunk.sourceId!) ?? [];
    list.push(chunk);
    bySource.set(chunk.sourceId!, list);
  }
  const topSources = [...bySource.entries()]
    .sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]))
    .slice(0, 3);
  for (const [sourceId, list] of topSources) {
    const title = list[0].sourceTitle;
    const label = title ? `《${title}》（${sourceId}）` : `（${sourceId}）`;
    sentences.push(sentence('source',
      `来源${label}贡献 ${list.length} 条，例如${examples(list)}。`, list));
  }

  const riskLevels: { level: 'high' | 'medium' | 'low'; label: string }[] = [
    { level: 'high', label: '高风险' },
    { level: 'medium', label: '中风险' },
    { level: 'low', label: '低风险' },
  ];
  const risked = group.filter((chunk) => chunk.riskLevel && chunk.riskBasis?.trim());
  if (risked.length) {
    const parts = riskLevels
      .map(({ level, label }) => ({ label, count: risked.filter((chunk) => chunk.riskLevel === level).length }))
      .filter((item) => item.count > 0)
      .map((item) => `${item.label}${item.count} 条`)
      .join('、');
    sentences.push(sentence('risk',
      `已评审风险标注中，${parts}，例如${examples(risked)}。`, risked));
  }

  const untagged = group.filter((chunk) =>
    !INFORMATION_TYPES.has(chunk.entryType ?? '') && !(chunk.roles?.length));
  if (untagged.length) {
    sentences.push(sentence('untagged',
      `其余 ${untagged.length} 条诊断条目尚未标注角色，未标注不表示没有该角色。`, untagged));
  }

  const report: CommunityReport = {
    id: JSON.stringify([brand, model, componentId]),
    brand,
    model,
    componentId,
    componentName,
    title: `${brand} ${model} · ${componentName}常见问题摘要`,
    entryCount: group.length,
    sourceCount: sources.size,
    sentences,
    kbVersion: snapshot.kbVersion,
    snapshotSha: snapshot.snapshotSha,
    status: 'current',
    limitations: [...COMMUNITY_REPORT_LIMITATIONS],
  };
  return Object.freeze(report);
}

/** Reports are cached per snapshot generation; a reloaded snapshot rebuilds them. */
export function communityReportsForSnapshot(snapshot: KnowledgeSnapshot): CommunityReportSet {
  const existing = cache.get(snapshot);
  if (existing) return existing;
  const result = buildCommunityReports(snapshot);
  cache.set(snapshot, result);
  return result;
}

export function getCommunityReports(): CommunityReportSet {
  return communityReportsForSnapshot(loadKnowledgeSnapshot());
}

/** A transported set is usable only when it still matches the live snapshot; otherwise it is stale, never silently old. */
export function checkCommunityReportSet(set: CommunityReportSet, snapshot: KnowledgeSnapshot): { status: 'current' | 'stale'; reason: string | null } {
  if (set.kbVersion === snapshot.kbVersion && set.snapshotSha === snapshot.snapshotSha) return { status: 'current', reason: null };
  const reason = describeCommunityReportStaleness(
    { kbVersion: set.kbVersion, snapshotSha: set.snapshotSha }, snapshot.kbVersion, snapshot.snapshotSha);
  return { status: 'stale', reason };
}

export { isCommunityReportCurrent };

/** Optional deterministic paging, mirroring the relations endpoint. */
export function pageCommunityReports(set: CommunityReportSet, params: URLSearchParams): CommunityReportSet {
  if (!params.has('offset') && !params.has('limit')) return set;
  if (params.getAll('offset').length > 1 || params.getAll('limit').length > 1) throw new RangeError('社区报告分页参数不能重复。');
  const rawOffset = params.get('offset') ?? '0';
  const rawLimit = params.get('limit') ?? '200';
  if (!/^(0|[1-9]\d{0,8})$/.test(rawOffset) || !/^[1-9]\d{0,4}$/.test(rawLimit)) throw new RangeError('社区报告分页参数无效。');
  const offset = Number(rawOffset);
  const limit = Number(rawLimit);
  if (limit > 1000 || offset > set.reports.length) throw new RangeError('社区报告分页超出范围。');
  return {
    ...set,
    reports: set.reports.slice(offset, offset + limit),
    page: { offset, limit, total: set.reports.length, hasMore: offset + limit < set.reports.length },
  };
}
