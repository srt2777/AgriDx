#!/usr/bin/env python3
"""Build reproducible LVGL Chinese fonts from pinned Noto Sans CJK SC.

Download the OTF linked in src/fonts/README.md, then run:
  python3 tools/gen_fonts.py --font /path/to/NotoSansCJKsc-Regular.otf
Requires Python fonttools and Node/npm. The source blob is verified before use.
16px covers U+4E00-9FEF (20,976 CJK characters); 12/22px include current UI literals.
"""
import argparse
import hashlib
from pathlib import Path
import re
import subprocess
import tempfile
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src/fonts"
SOURCE_COMMIT = "f8d157532fbfaeda587e826d4cd5b21a49186f7c"
SOURCE_BLOB = "dc15562470b4f842321894787a0d066879ccff8b"
CONVERTER = "lv_font_conv@1.5.3"
SYMBOLS = "℃°±×÷≈λΔμ…—·（）、，。：；“”‘’《》→←↑↓√"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--font", required=True, type=Path)
parser.add_argument("--sizes", nargs="+", type=int, choices=(12, 16, 22), default=[16, 22, 12],
                    help="Font sizes to regenerate; use --sizes 12 22 for UI-only changes")
parser.add_argument("--out-dir", type=Path, default=OUT, help="Output directory (supports isolated size trials)")
compression = parser.add_mutually_exclusive_group()
compression.add_argument("--compress", dest="compress", action="store_true", help="Use RLE (smaller flash, extra decode work)")
compression.add_argument("--no-compress", dest="compress", action="store_false", help="Use plain 4bpp bitmaps (default)")
parser.set_defaults(compress=False)
args = parser.parse_args()
OUT = args.out_dir.resolve()
OUT.mkdir(parents=True, exist_ok=True)
font_path = args.font.resolve()
data = font_path.read_bytes()
blob = hashlib.sha1(f"blob {len(data)}\0".encode() + data).hexdigest()
if blob != SOURCE_BLOB:
    raise SystemExit(f"Source font mismatch: expected Git blob {SOURCE_BLOB}, got {blob}")
font = TTFont(font_path)
cmap = font.getBestCmap()

# Tokenize comments and string literals together so Chinese comments never
# accidentally become UI requirements. Only these public source files are read.
ui = set(SYMBOLS)
tokens = re.compile(r'//[^\n]*|/\*[\s\S]*?\*/|"(?:\\.|[^"\\])*"')
for source_path in sorted((ROOT / "src").glob("*.cpp")):
    for token in tokens.findall(source_path.read_text()):
        if token.startswith('"'):
            ui.update(ch for ch in token[1:-1] if ord(ch) > 126)
missing = sorted(ch for ch in ui if ord(ch) not in cmap)
if missing:
    raise SystemExit("Source lacks required UI characters: " + "".join(missing))
ui_text = "".join(sorted(ui))
missing_cjk = [cp for cp in range(0x4e00, 0x9ff0) if cp not in cmap]
if missing_cjk:
    raise SystemExit(f"Source lacks {len(missing_cjk)} basic CJK characters")

# All generated files carry the same source attribution; the distributed OFL
# text lives beside them. Generate in temp files and replace each only on success.
for size in dict.fromkeys(args.sizes):
    name = f"font_zh_{size}"
    ranges = "0x20-0x7E,0x4E00-0x9FEF" if size == 16 else "0x20-0x7E"
    with tempfile.TemporaryDirectory(prefix="agridx-font-convert-") as tmp:
        target = Path(tmp) / f"{name}.c"
        command = ["npx", "--yes", CONVERTER, "--font", str(font_path),
                   "--size", str(size), "--format", "lvgl", "--bpp", "4",
                   "--output", str(target), "--symbols", ui_text,
                   "--range", ranges, "--lv-font-name", name, "--no-kerning"]
        if not args.compress:
            command.append("--no-compress")
        subprocess.run(command, check=True)
        text = target.read_text().replace('#include "lvgl/lvgl.h"', '#include "lvgl.h"')
        # Avoid machine-specific paths in the generated command comment.
        text = text.replace(str(font_path), "NotoSansCJKsc-Regular.otf")
        text = text.replace(str(target), f"src/fonts/{name}.c")
        notice = (f"/* Source: Noto Sans CJK SC Regular, SIL OFL 1.1; see OFL-NotoSansCJK.txt.\n"
                  f" * Upstream commit: {SOURCE_COMMIT}; Git blob: {SOURCE_BLOB}.\n"
                  f" * Generated by {CONVERTER}; rerun tools/gen_fonts.py. */\n")
        (OUT / f"{name}.c").write_text(notice + text)
        print(f"Generated {name}: {len(text):,} source bytes; ranges {ranges}; {len(ui)} UI characters", flush=True)
print("Run python3 tools/check_fonts.py to validate actual LVGL glyph decoding.")
